type Option = [string, string, string, string];
let nextId = 37;
function Q(
  segmentId: string,
  type: string,
  en: string,
  ar: string,
  correct: number,
  options: Option[],
): Question {
  const s = segments.find((s) => s.id === segmentId)!;
  return {
    id: `m${nextId++}`,
    segmentId,
    topic: s.topic,
    type,
    stem: en,
    ar,
    options: options.map((o) => o[0]),
    arOptions: options.map((o) => o[1]),
    correct,
    why: options[correct][2],
    arWhy: options[correct][3],
    distractors: options.map((o) => o[2]),
    arDistractors: options.map((o) => o[3]),
    citations: s.citations,
  };
}
